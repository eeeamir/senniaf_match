CREATE TABLE public.seguimientos_vinculacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculacion_id bigint NOT NULL REFERENCES public.vinculaciones(id),
    autor varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
    nombre_autor text NOT NULL,
    rol varchar(25) NOT NULL CHECK (rol IN ('TRABAJADOR_SOCIAL', 'PSICOLOGO')),
    clave_registro uuid NOT NULL,
    fecha_atencion date NOT NULL,
    etapa varchar(30) NOT NULL CHECK (etapa IN ('ENCUENTROS_PREVIOS', 'CONVIVENCIA_PREADOPTIVA')),
    contenido text NOT NULL CHECK (jsonb_typeof(contenido::jsonb) = 'object'),
    registrado timestamp with time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    UNIQUE (vinculacion_id, autor, clave_registro),
    UNIQUE (vinculacion_id, id)
);
CREATE INDEX seguimientos_vinculacion_por_atencion
    ON public.seguimientos_vinculacion(vinculacion_id, fecha_atencion DESC, id DESC);

CREATE TABLE public.seguimientos_vinculacion_historial (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculacion_id bigint NOT NULL,
    seguimiento_id bigint NOT NULL,
    actor varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
    nombre_actor text NOT NULL,
    rol varchar(25) NOT NULL CHECK (rol IN ('TRABAJADOR_SOCIAL', 'PSICOLOGO')),
    fecha timestamp with time zone NOT NULL,
    accion varchar(15) NOT NULL CHECK (accion IN ('REGISTRADO', 'MODIFICADO')),
    cambios text NOT NULL CHECK (jsonb_typeof(cambios::jsonb) = 'object'),
    motivo varchar(1000),
    FOREIGN KEY (vinculacion_id, seguimiento_id) REFERENCES public.seguimientos_vinculacion(vinculacion_id, id)
);
CREATE INDEX seguimientos_vinculacion_historial_por_fecha
    ON public.seguimientos_vinculacion_historial(vinculacion_id, fecha DESC, id DESC);

