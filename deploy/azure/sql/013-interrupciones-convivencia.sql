SELECT current_database() = :'base_autorizada' AND :'confirmacion' = 'AGREGAR_INTERRUPCIONES_SIN_BORRAR' AS destino_confirmado \gset
\if :destino_confirmado
BEGIN;
SET LOCAL lock_timeout='5s';
CREATE TABLE public.interrupciones_convivencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculacion_id bigint NOT NULL UNIQUE REFERENCES public.vinculaciones(id),
    fecha_interrupcion date NOT NULL,
    referencia_actuacion varchar(200) NOT NULL CHECK(length(btrim(referencia_actuacion)) BETWEEN 5 AND 200),
    justificacion varchar(2000) NOT NULL CHECK(length(btrim(justificacion)) BETWEEN 10 AND 2000),
    registrado_por varchar(40) NOT NULL,
    rol_profesional varchar(25) NOT NULL CHECK(rol_profesional IN ('TRABAJADOR_SOCIAL','PSICOLOGO')),
    fecha_registro timestamp(6) NOT NULL,
    revision_justificacion varchar(2000),
    revisado_por varchar(40),
    fecha_revision timestamp(6),
    version bigint NOT NULL DEFAULT 0,
    CHECK ((revision_justificacion IS NULL AND revisado_por IS NULL AND fecha_revision IS NULL)
       OR (revision_justificacion IS NOT NULL AND length(btrim(revision_justificacion)) BETWEEN 10 AND 2000 AND revisado_por IS NOT NULL AND fecha_revision IS NOT NULL))
);
DO $$ BEGIN
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='senniaf_app') THEN
        GRANT SELECT,INSERT ON public.interrupciones_convivencia TO senniaf_app;
        GRANT UPDATE(revision_justificacion,revisado_por,fecha_revision,version) ON public.interrupciones_convivencia TO senniaf_app;
        GRANT USAGE,SELECT ON SEQUENCE public.interrupciones_convivencia_id_seq TO senniaf_app;
    END IF;
END $$;
COMMIT;
\else
