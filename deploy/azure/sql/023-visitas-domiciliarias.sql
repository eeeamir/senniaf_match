-- Migración aditiva de visitas domiciliarias compartidas.
SELECT current_database() = :'base_autorizada' AND :'confirmacion' = 'CREAR_VISITAS_DOMICILIARIAS' AS destino_confirmado \gset
\if :destino_confirmado
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE public.visitas_domiciliarias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculacion_id bigint NOT NULL REFERENCES public.vinculaciones(id),
    autor varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
    rol varchar(25) NOT NULL CHECK (rol IN ('TRABAJADOR_SOCIAL', 'PSICOLOGO')),
    registrado timestamptz NOT NULL,
    clave_registro uuid NOT NULL,
    fecha date NOT NULL,
    inicio time without time zone NOT NULL,
    fin time without time zone NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    CHECK (fin > inicio AND inicio < time '24:00' AND fin < time '24:00'
           AND EXTRACT(SECOND FROM inicio) = 0 AND EXTRACT(SECOND FROM fin) = 0),
    UNIQUE (vinculacion_id, autor, clave_registro),
    UNIQUE (vinculacion_id, fecha, inicio)
);

CREATE TABLE public.visitas_domiciliarias_historial (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_id bigint NOT NULL REFERENCES public.visitas_domiciliarias(id),
    actor varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
    nombre_actor text NOT NULL,
    rol varchar(25) NOT NULL CHECK (rol IN ('TRABAJADOR_SOCIAL', 'PSICOLOGO')),
    fecha timestamptz NOT NULL,
    accion varchar(15) NOT NULL CHECK (accion IN ('REGISTRADA','MODIFICADA')),
    cambios text NOT NULL CHECK (jsonb_typeof(cambios::jsonb) = 'object'),
    motivo varchar(1000)
);
CREATE INDEX visitas_domiciliarias_historial_por_visita ON public.visitas_domiciliarias_historial(visita_id, fecha DESC, id DESC);

CREATE TRIGGER visitas_domiciliarias_historial_inmutable
    BEFORE UPDATE OR DELETE ON public.visitas_domiciliarias_historial
    FOR EACH ROW EXECUTE FUNCTION public.conservar_historial_seguimientos_vinculacion();

GRANT SELECT, INSERT ON public.visitas_domiciliarias, public.visitas_domiciliarias_historial TO senniaf_app;
GRANT UPDATE (fecha, inicio, fin, version) ON public.visitas_domiciliarias TO senniaf_app;
GRANT USAGE, SELECT ON SEQUENCE public.visitas_domiciliarias_id_seq, public.visitas_domiciliarias_historial_id_seq TO senniaf_app;
COMMIT;
\else
DO $$ BEGIN RAISE EXCEPTION 'Destino o confirmación incorrectos'; END $$;
\endif
