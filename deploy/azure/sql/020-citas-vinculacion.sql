CREATE TABLE public.citas_vinculacion (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vinculacion_id bigint NOT NULL REFERENCES public.vinculaciones(id),
 profesional varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
 creado_por varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
 motivo varchar(30) NOT NULL CHECK(motivo IN ('ORIENTACION','SEGUIMIENTO','ENCUENTRO','OBSERVACION','DUDAS','OTRO')),
 estado varchar(25) NOT NULL CHECK(estado IN ('PENDIENTE','CONFIRMADA','CAMBIO_PROPUESTO','RECHAZADA','CANCELADA','REALIZADA')),
 inicio timestamp without time zone NOT NULL, fin timestamp without time zone NOT NULL,
 duracion integer NOT NULL CHECK(duracion IN (60,120)),
 mensaje_inicial varchar(1000) NOT NULL CHECK(char_length(btrim(mensaje_inicial)) BETWEEN 10 AND 1000),
 mensaje varchar(1000) NOT NULL CHECK(char_length(btrim(mensaje)) BETWEEN 10 AND 1000),
 respuesta varchar(1000), ultimo_rol varchar(30) NOT NULL CHECK(ultimo_rol IN ('FAMILIA','TRABAJADOR_SOCIAL')),
 creada timestamp with time zone NOT NULL, actualizada timestamp with time zone NOT NULL,
 version bigint NOT NULL DEFAULT 0,
 CONSTRAINT citas_intervalo_check CHECK(fin=inicio+duracion*interval '1 minute' AND inicio::date=fin::date)
);
CREATE UNIQUE INDEX citas_una_abierta_por_vinculacion ON public.citas_vinculacion(vinculacion_id) WHERE estado IN ('PENDIENTE','CAMBIO_PROPUESTO');
CREATE INDEX citas_agenda_confirmada ON public.citas_vinculacion(profesional,inicio,fin) WHERE estado='CONFIRMADA';
CREATE INDEX citas_vinculacion_recientes ON public.citas_vinculacion(vinculacion_id,actualizada DESC,id DESC);
CREATE TABLE public.citas_historial (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cita_id bigint NOT NULL REFERENCES public.citas_vinculacion(id),
 actor varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
 rol varchar(30) NOT NULL CHECK(rol IN ('FAMILIA','TRABAJADOR_SOCIAL')),
 profesional varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
 accion varchar(30) NOT NULL, anterior varchar(25), nuevo varchar(25) NOT NULL,
 motivo_respuesta varchar(40), mensaje varchar(1000) NOT NULL,
 inicio timestamp without time zone NOT NULL, fin timestamp without time zone NOT NULL,
 duracion integer NOT NULL CHECK(duracion IN (60,120)), fecha timestamp with time zone NOT NULL,
 CHECK(fin=inicio+duracion*interval '1 minute')
);
CREATE INDEX citas_historial_por_cita ON public.citas_historial(cita_id,id);
CREATE FUNCTION public.conservar_historial_citas() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'El historial de citas es inmutable' USING ERRCODE='23514'; END $$;
CREATE TRIGGER citas_historial_inmutable BEFORE UPDATE OR DELETE ON public.citas_historial FOR EACH ROW EXECUTE FUNCTION public.conservar_historial_citas();
GRANT SELECT,INSERT,UPDATE ON public.citas_vinculacion TO senniaf_app;
GRANT SELECT,INSERT ON public.citas_historial TO senniaf_app;
GRANT USAGE,SELECT ON SEQUENCE public.citas_vinculacion_id_seq,public.citas_historial_id_seq TO senniaf_app;
REVOKE DELETE ON public.citas_vinculacion FROM senniaf_app;
REVOKE UPDATE,DELETE ON public.citas_historial FROM senniaf_app;
COMMIT;
