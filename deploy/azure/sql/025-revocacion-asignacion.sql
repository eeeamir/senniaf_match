-- Incidencias de asignación independientes de la convivencia, sin reclasificar cierres anteriores.
SELECT current_database() = :'base_autorizada' AND :'confirmacion' = 'HABILITAR_REVOCACION_ASIGNACION' AS destino_confirmado \gset
\if :destino_confirmado
BEGIN;
SET LOCAL lock_timeout = '5s';

ALTER TABLE public.vinculaciones DROP CONSTRAINT vinculaciones_resultado_cierre_check;
ALTER TABLE public.vinculaciones ADD CONSTRAINT vinculaciones_resultado_cierre_check CHECK (
    resultado_cierre IS NULL OR (estado = 'CERRADA' AND resultado_cierre IN
        ('ADOPCION_FORMALIZADA', 'INTERRUPCION_CONVIVENCIA', 'CIERRE_DOCUMENTADO', 'REVOCACION_ASIGNACION'))
);

CREATE TABLE public.incidencias_asignacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculacion_id bigint NOT NULL REFERENCES public.vinculaciones(id),
    motivo varchar(32) NOT NULL CHECK (motivo IN ('DESISTIMIENTO_FAMILIA','RECHAZO_NINO','OTRO')),
    justificacion varchar(2000) NOT NULL CHECK (length(btrim(justificacion)) >= 10),
    registrado_por varchar(40) NOT NULL REFERENCES public.usuarios(identificador),
    fecha_registro timestamp without time zone NOT NULL,
    procede_revocacion boolean,
    fundamento_revision varchar(2000),
    revisado_por varchar(40) REFERENCES public.usuarios(identificador),
    fecha_revision timestamp without time zone,
    CONSTRAINT incidencia_revision_completa CHECK (
        (procede_revocacion IS NULL AND fundamento_revision IS NULL AND revisado_por IS NULL AND fecha_revision IS NULL)
        OR (procede_revocacion IS NOT NULL AND fundamento_revision IS NOT NULL AND length(btrim(fundamento_revision)) >= 10
            AND revisado_por IS NOT NULL AND fecha_revision IS NOT NULL)
    )
);
CREATE UNIQUE INDEX incidencias_asignacion_bloqueo ON public.incidencias_asignacion(vinculacion_id)
    WHERE procede_revocacion IS DISTINCT FROM false;
GRANT SELECT, INSERT ON public.incidencias_asignacion TO senniaf_app;
GRANT UPDATE (procede_revocacion, fundamento_revision, revisado_por, fecha_revision)
    ON public.incidencias_asignacion TO senniaf_app;
GRANT USAGE, SELECT ON SEQUENCE public.incidencias_asignacion_id_seq TO senniaf_app;
COMMIT;
\else
DO $$ BEGIN RAISE EXCEPTION 'Destino o confirmación incorrectos.'; END $$;
\endif
