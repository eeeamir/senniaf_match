-- Conserva resultados históricos sin clasificar y registra las nuevas solicitudes familiares.
SELECT current_database() = :'base_autorizada' AND :'confirmacion' = 'HABILITAR_CIERRE_Y_REINCORPORACION' AS destino_confirmado \gset
\if :destino_confirmado
BEGIN;
SET LOCAL lock_timeout = '5s';

ALTER TABLE public.vinculaciones ADD COLUMN resultado_cierre varchar(32);
ALTER TABLE public.vinculaciones ADD CONSTRAINT vinculaciones_resultado_cierre_check CHECK (
    resultado_cierre IS NULL OR (estado = 'CERRADA' AND resultado_cierre IN
        ('ADOPCION_FORMALIZADA', 'INTERRUPCION_CONVIVENCIA', 'CIERRE_DOCUMENTADO'))
);
GRANT UPDATE (resultado_cierre) ON public.vinculaciones TO senniaf_app;

CREATE TABLE public.solicitudes_reincorporacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculacion_id bigint NOT NULL UNIQUE REFERENCES public.vinculaciones(id),
    solicitada timestamp without time zone NOT NULL,
    entrevista_actualizada timestamp without time zone,
    autorizada boolean,
    resuelta timestamp without time zone,
    resuelto_por varchar(40) REFERENCES public.usuarios(identificador),
    fundamento varchar(2000),
    CONSTRAINT reincorporacion_resolucion_completa CHECK (
        (autorizada IS NULL AND resuelta IS NULL AND resuelto_por IS NULL AND fundamento IS NULL)
        OR (autorizada IS NOT NULL AND resuelta IS NOT NULL AND resuelto_por IS NOT NULL
            AND fundamento IS NOT NULL AND length(btrim(fundamento)) >= 10 AND entrevista_actualizada IS NOT NULL)
    )
);
GRANT SELECT, INSERT ON public.solicitudes_reincorporacion TO senniaf_app;
GRANT UPDATE (entrevista_actualizada, autorizada, resuelta, resuelto_por, fundamento)
    ON public.solicitudes_reincorporacion TO senniaf_app;
GRANT USAGE, SELECT ON SEQUENCE public.solicitudes_reincorporacion_id_seq TO senniaf_app;

COMMIT;
\else
DO $$ BEGIN RAISE EXCEPTION 'Destino o confirmación incorrectos.'; END $$;
\endif
