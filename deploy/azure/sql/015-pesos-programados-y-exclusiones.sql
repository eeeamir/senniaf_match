-- Ampliación aditiva: programaciones persistentes y exclusiones por combinación.
SELECT current_database() = :'base_autorizada' AND :'confirmacion' = 'PROGRAMAR_PESOS_SIN_BORRAR' AS destino_confirmado \gset
\if :destino_confirmado
BEGIN;
SET LOCAL lock_timeout='5s';
CREATE TABLE programaciones_pesos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 responsable varchar(40) NOT NULL, justificacion varchar(300) NOT NULL CHECK(length(btrim(justificacion)) BETWEEN 10 AND 300),
 anteriores text NOT NULL, nuevos text NOT NULL,
 version_anterior integer NOT NULL,version_nueva integer NOT NULL CHECK(version_nueva=version_anterior+1),
 programada_el timestamp(6) with time zone NOT NULL, activar_el timestamp(6) with time zone NOT NULL,
 activada_el timestamp(6) with time zone,estado varchar(20) NOT NULL CHECK(estado IN ('PENDIENTE','APLICADA')),
 CHECK(activar_el>=programada_el+interval '24 hours'),
 CHECK((activar_el AT TIME ZONE 'America/Panama')::time=time '07:00:00'),
 CHECK((estado='PENDIENTE' AND activada_el IS NULL) OR (estado='APLICADA' AND activada_el IS NOT NULL AND activada_el>=activar_el))
);
CREATE UNIQUE INDEX uk_programacion_pendiente ON programaciones_pesos((1)) WHERE estado='PENDIENTE';
CREATE TABLE combinaciones_excluidas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo_nino varchar(24) NOT NULL,codigo_familia varchar(24) NOT NULL,
 origen varchar(20) NOT NULL,responsable varchar(40) NOT NULL,fecha timestamp(6) NOT NULL,
 UNIQUE(codigo_nino,codigo_familia)
);
-- Los rechazos anteriores siguen excluidos aunque posteriormente se haya cerrado la vinculación.
INSERT INTO combinaciones_excluidas(codigo_nino,codigo_familia,origen,responsable,fecha)
SELECT DISTINCT ON(codigo_nino,codigo_familia) codigo_nino,codigo_familia,'COMITE',funcionario,fecha
FROM decisiones_comite WHERE decision='DESCARTADA' ORDER BY codigo_nino,codigo_familia,id
ON CONFLICT DO NOTHING;
INSERT INTO combinaciones_excluidas(codigo_nino,codigo_familia,origen,responsable,fecha)
SELECT DISTINCT ON(n.codigo_caso,f.codigo_caso) n.codigo_caso,f.codigo_caso,'FAMILIA',coalesce(v.respondido_por,'HISTORICO'),coalesce(v.fecha_respuesta,d.fecha)
FROM vinculaciones v JOIN perfiles_nino n ON n.id=v.nino_id JOIN perfiles_familia f ON f.id=v.familia_id JOIN decisiones_comite d ON d.id=v.decision_id
WHERE v.estado='RESPUESTA_RECHAZADA_PENDIENTE_CIERRE' OR EXISTS(
 SELECT 1 FROM auditoria_casos a WHERE a.accion='RESPUESTA_FAMILIAR' AND CASE WHEN pg_input_is_valid(a.descripcion,'jsonb') THEN (a.descripcion::jsonb)->>'vinculacionId'=v.id::text AND (a.descripcion::jsonb)->>'estado'='RESPUESTA_RECHAZADA_PENDIENTE_CIERRE' ELSE false END)
ORDER BY n.codigo_caso,f.codigo_caso,v.id ON CONFLICT DO NOTHING;
ALTER TABLE vinculaciones DROP CONSTRAINT vinculaciones_estado_check;
ALTER TABLE vinculaciones DROP CONSTRAINT vinculaciones_respuesta_check;
ALTER TABLE vinculaciones ADD CONSTRAINT vinculaciones_estado_check CHECK(estado IN ('PENDIENTE_RESPUESTA','RESPUESTA_ACEPTADA','RESPUESTA_RECHAZADA_PENDIENTE_CIERRE','CERRADA','RECHAZADA_POR_FAMILIA'));
ALTER TABLE vinculaciones ADD CONSTRAINT vinculaciones_respuesta_check CHECK(estado='CERRADA' OR (estado='PENDIENTE_RESPUESTA' AND fecha_respuesta IS NULL AND respondido_por IS NULL) OR (estado IN ('RESPUESTA_ACEPTADA','RESPUESTA_RECHAZADA_PENDIENTE_CIERRE','RECHAZADA_POR_FAMILIA') AND fecha_respuesta IS NOT NULL AND respondido_por IS NOT NULL));
-- No se altera el estado ni la respuesta histórica. Solo se levanta la reserva de propuestas sin actuaciones de convivencia/cierre.
UPDATE vinculaciones v SET reserva_vigente=false WHERE estado='RESPUESTA_RECHAZADA_PENDIENTE_CIERRE' AND fecha_cierre IS NULL AND NOT EXISTS(SELECT 1 FROM interrupciones_convivencia i WHERE i.vinculacion_id=v.id);
DO $$ BEGIN IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='senniaf_app') THEN
 GRANT SELECT,INSERT ON combinaciones_excluidas TO senniaf_app;
 GRANT SELECT,INSERT ON programaciones_pesos TO senniaf_app;
 GRANT UPDATE(estado,activada_el) ON programaciones_pesos TO senniaf_app;
 GRANT USAGE,SELECT ON SEQUENCE programaciones_pesos_id_seq,combinaciones_excluidas_id_seq TO senniaf_app;
END IF;END $$;
COMMIT;
\else
DO $$ BEGIN RAISE EXCEPTION 'Destino o confirmación incorrectos. No se modificó el esquema.';END $$;
\endif
