-- psql -X -v ON_ERROR_STOP=1 -v base_autorizada=BASE_REVISADA -v confirmacion=CREAR_VINCULACIONES_SIN_BORRAR -f 012-vinculaciones.sql
SELECT current_database() = :'base_autorizada' AND :'confirmacion' = 'CREAR_VINCULACIONES_SIN_BORRAR' AS destino_confirmado \gset
\if :destino_confirmado
BEGIN;
SET LOCAL lock_timeout = '5s';
-- Evita escrituras durante la conversión; el despliegue debe detener el código anterior.
LOCK TABLE decisiones_comite, perfiles_nino, perfiles_familia IN SHARE ROW EXCLUSIVE MODE;
CREATE TABLE vinculaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_id bigint NOT NULL UNIQUE REFERENCES decisiones_comite(id),
    nino_id bigint NOT NULL REFERENCES perfiles_nino(id),
    familia_id bigint NOT NULL REFERENCES perfiles_familia(id),
    estado varchar(60) NOT NULL CHECK (estado IN ('PENDIENTE_RESPUESTA','RESPUESTA_ACEPTADA','RESPUESTA_RECHAZADA_PENDIENTE_CIERRE')),
    reserva_vigente boolean NOT NULL DEFAULT true,
    fecha_respuesta timestamp(6),
    respondido_por varchar(40),
    version bigint NOT NULL DEFAULT 0,
    CHECK ((estado = 'PENDIENTE_RESPUESTA' AND fecha_respuesta IS NULL AND respondido_por IS NULL)
        OR (estado <> 'PENDIENTE_RESPUESTA' AND fecha_respuesta IS NOT NULL AND respondido_por IS NOT NULL))
);
CREATE UNIQUE INDEX uk_vinculacion_nino_reservado ON vinculaciones(nino_id) WHERE reserva_vigente;
CREATE UNIQUE INDEX uk_vinculacion_familia_reservada ON vinculaciones(familia_id) WHERE reserva_vigente;
-- Reutiliza únicamente decisiones reales existentes. Si hay conflictos históricos,
-- los índices abortan la migración completa; no se elige una asignación arbitraria.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM decisiones_comite d
        LEFT JOIN perfiles_nino n ON n.codigo_caso=d.codigo_nino
        LEFT JOIN perfiles_familia f ON f.codigo_caso=d.codigo_familia
        WHERE d.decision='ACEPTADA' AND (n.id IS NULL OR f.id IS NULL OR d.fecha IS NULL)
    ) THEN
        RAISE EXCEPTION 'Hay aceptaciones sin expedientes o fecha: revisar antes de migrar';
    END IF;
END $$;
INSERT INTO vinculaciones(decision_id,nino_id,familia_id,estado)
SELECT d.id,n.id,f.id,'PENDIENTE_RESPUESTA' FROM decisiones_comite d
JOIN perfiles_nino n ON n.codigo_caso=d.codigo_nino
JOIN perfiles_familia f ON f.codigo_caso=d.codigo_familia
WHERE d.decision='ACEPTADA';
-- La cuenta técnica existente no hereda permisos sobre tablas creadas después de 002.
-- No se crean cuentas ni se conceden permisos de borrado o edición del historial.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='senniaf_app') THEN
        GRANT SELECT, INSERT, UPDATE ON public.vinculaciones TO senniaf_app;
        GRANT USAGE, SELECT ON SEQUENCE public.vinculaciones_id_seq TO senniaf_app;
    END IF;
END $$;
COMMIT;
\else
DO $$ BEGIN RAISE EXCEPTION 'Destino o confirmación incorrectos. No se modificó el esquema.'; END $$;
\endif
